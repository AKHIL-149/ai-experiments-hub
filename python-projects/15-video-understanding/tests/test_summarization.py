# Integration Tests

def test_full_summarization_pipeline(mock_llm_client, sample_scenes, sample_transcript):
    """Test full summarization pipeline"""
    # 1. Video summary
    video_summarizer = VideoSummarizer(llm_client=mock_llm_client)
    video_summary = video_summarizer.summarize_video(
        video_id="test_video",
        duration=35.0,
        transcript=sample_transcript,
        scenes=sample_scenes,
    )

    assert video_summary is not None

    # 2. Scene summaries
    scene_summarizer = SceneSummarizer(llm_client=mock_llm_client)
    scene_summaries = scene_summarizer.summarize_scenes_batch(sample_scenes)

    assert len(scene_summaries) == 3

    # 3. Chapters
    chapter_generator = ChapterGenerator()
    chapters = chapter_generator.generate_chapters(
        video_id="test_video",
        duration=35.0,
        scenes=sample_scenes,
    )

    assert len(chapters.chapters) > 0

    # 4. Format with templates
    template_manager = SummaryTemplateManager()
    formatted_video = template_manager.format_video_summary(
        video_summary,
        template_name="markdown",
    )
    formatted_chapters = template_manager.format_chapters(
        chapters,
        template_name="markdown",
    )

    assert formatted_video is not None
    assert formatted_chapters is not None


def test_cost_tracking(mock_llm_client, sample_transcript):
    """Test cost tracking across summarization"""
    summarizer = VideoSummarizer(llm_client=mock_llm_client)

    # Generate multiple summaries
    summaries = []
    for i in range(3):
        summary = summarizer.summarize_video(
            video_id=f"video_{i}",
            duration=35.0,
            transcript=sample_transcript,
        )
        summaries.append(summary)

    # Check total cost
    total_cost = sum(s.cost_usd for s in summaries)
    assert total_cost > 0
    assert total_cost == 0.003  # 3 * 0.001
